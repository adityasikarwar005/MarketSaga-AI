@pytest.fixture(autouse=True)
def _the_published_dashboard_is_off_limits():
    """No test may add, change or remove a file in `services/dashboard`.

    That directory is what gets uploaded to a public Space. Nothing in it is
    generated by the suite and nothing in it should be touched by the suite, and
    the way it got touched is worth stating because it is not obvious from any
    one line.

    `close_out.main` cleared superseded chart payloads out of the real output
    directory and then called `chart_history.write`. Its tests stub `write` -
    correctly, they are about which underlyings get built - but stubbing `write`
    does not stub the `unlink` loop standing next to it. So every run of the
    suite deleted the day's payloads from a real, published directory. Nothing
    failed. The tests passed. The page kept its ladder, because the index is a
    separate file, and lost every candle behind it.

    The deletion has moved inside `write`, where a stubbed `write` cannot reach
    it. This is the fence, for the next destructive step that gets written a
    caller away from the thing that stubs it.
    """
    root = Path(__file__).resolve().parents[1] / "services" / "dashboard"
    before = {p.name: p.stat().st_mtime_ns for p in root.glob("*")} if root.exists() else {}
    yield
    after = {p.name: p.stat().st_mtime_ns for p in root.glob("*")} if root.exists() else {}
    if before != after:
        gone = sorted(set(before) - set(after))
        added = sorted(set(after) - set(before))
        changed = sorted(k for k in before.keys() & after.keys() if before[k] != after[k])
        raise AssertionError(
            "this test modified services/dashboard, which is published to a "
            "public Space and is not the suite's to write:"
            + (f"\n  deleted: {', '.join(gone)}" if gone else "")
            + (f"\n  added:   {', '.join(added)}" if added else "")
            + (f"\n  changed: {', '.join(changed)}" if changed else "")
            + "\nUse tmp_path. If a job under test writes there, its output "
            "directory has to be injectable rather than a module constant."
        )
